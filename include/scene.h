#pragma once 
#include "common.h"
#include <vector>
#include <string>

// ======================================================================================
// 1. 物体结构体 (Object) - 纯三角形架构
// ======================================================================================
// [内存布局优化]
// 总大小: 176 字节 (16 的倍数)。
// 我们按照数据类型大小降序排列，以保证内存紧凑且对齐。
// --------------------------------------------------------------------------------------
struct Object {
    // --- [16字节类型] 几何数据 (96 bytes) ---
    Vec v0, v1, v2;    // 顶点位置 (Vertices)
    Vec vn0, vn1, vn2; // 顶点法线 (Vertex Normals, 用于平滑着色)
    
    // --- [16字节类型] 颜色数据 (32 bytes) ---
    Vec albedo;        // 基础颜色 / 反射率
    Vec emission;      // 自发光强度

    // --- [8字节类型] 纹理坐标 (24 bytes) ---
    Vec2 uv0, uv1, uv2; // 纹理坐标 (Texture Coordinates)

    // --- [4字节类型] 材质参数 (24 bytes) ---
    // 凑齐 6 个 4字节变量 = 24 字节
    
    float metallic;     // 金属度 [0.0 - 1.0]
    float roughness;    // 粗糙度 [0.0 - 1.0]
    float ior;          // 折射率 (Index of Refraction)
    float transmission; // 透射度 [0.0 - 1.0]
    
    int tex_id;         // 纹理ID (-1 表示无纹理)
    int use_smooth;     // 平滑开关 (1=使用顶点法线插值, 0=使用面法线)
    
    // 目前总计: 96 + 32 + 24 + 24 = 176 字节。
    // 完美对齐，不需要显式 Padding。
};

// ======================================================================================
// 2. 相机参数
// ======================================================================================
struct CameraParams {
    Vec pos; // 位置
    Vec cx;  // 视口 X 轴
    Vec cy;  // 视口 Y 轴
    Vec dir; // 朝向
    
    float lens_radius; // 光圈半径
    float focus_dist;  // 焦距
};

// ======================================================================================
// 4. 场景容器
// ======================================================================================
struct Scene {
    std::vector<Object> objects;
    std::vector<std::string> texture_files;
};

